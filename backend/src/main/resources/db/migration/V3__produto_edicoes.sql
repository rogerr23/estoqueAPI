-- Registro das edições de produto feitas por administradores (visível a todos).
CREATE TABLE produto_edicoes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 produto_id BIGINT NOT NULL REFERENCES produtos(id),
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
 alteracoes VARCHAR(2000) NOT NULL CHECK (btrim(alteracoes) <> '')
);
CREATE INDEX idx_produto_edicoes_data_hora ON produto_edicoes(data_hora DESC, id DESC);
CREATE INDEX idx_produto_edicoes_usuario ON produto_edicoes(usuario_id);
