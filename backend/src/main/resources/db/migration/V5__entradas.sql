-- Entrada de mercadoria: unidades que chegam a uma loja (compra, reposição etc.).
CREATE TABLE entradas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 produto_id BIGINT NOT NULL REFERENCES produtos(id),
 loja_id BIGINT NOT NULL REFERENCES lojas(id),
 quantidade INTEGER NOT NULL CHECK (quantidade > 0),
 observacao VARCHAR(200),
 data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id)
);
CREATE INDEX idx_entradas_data_hora ON entradas(data_hora DESC, id DESC);
CREATE INDEX idx_entradas_usuario ON entradas(usuario_id);
